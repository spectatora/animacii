# -*- coding: utf-8 -*-
"""Нормализация на заглавия.

Тук проектът живее или умира. Детерминирана функция, без LLM, покрита с тестове.

Правилата НЕ са измислени предварително — извлечени са от 1772 реални заглавия
от 11 детски канала (виж docs/PHASE0.md). Реалните данни имат три граматики:

  1. `ЗАГЛАВИЕ, сез.N, еп.M - Име на епизод, ГОДИНА. Описание...`
     (Cartoon Network, Cartoonito, Nickelodeon, Nicktoons, Nick Jr.)
  2. `ЗАГЛАВИЕ - Име на епизод`
     (Disney Channel, Disney Junior, e-Kids)
  3. `ЗАГЛАВИЕ`
     (Duck TV, Baby TV, Da Vinci Learning)

Редът на операциите има значение. Заглавието на предаването само по себе си може
да съдържа " - ":

    "СуперТингс: Съперници на Кабуум - Казуум сила, сез.1, еп.41 - Спининг битка"

Затова рязането по `, сез.` става ПРЕДИ рязането по тире, и когато е сработило,
тирето изобщо не се пипа.
"""

from __future__ import annotations

import re
import unicodedata

# --- 2. Уеднаквяване на кавички и тирета -----------------------------------

_QUOTES = {
    "„": '"', "“": '"', "”": '"', "‟": '"',
    "«": '"', "»": '"', "″": '"',
    "‘": "'", "’": "'", "‚": "'", "′": "'",
}
_DASHES = {
    "–": "-", "—": "-", "‒": "-", "―": "-",
    "−": "-", "‐": "-", "‑": "-",
}
_PUNCT = {**_QUOTES, **_DASHES, " ": " ", "…": "..."}

# --- 3. Хомоглифи ----------------------------------------------------------
# Източникът смесва латиница в кирилски думи: "Бeбeто", "Вeсeлата", "Цвeтни".
# Визуално неразличимо, но за string match са различни низове — тихо раздвоява
# едно предаване на две. Само истински визуални двойници; `t`/`l`/`r` НЕ са
# такива и идват от законно смесени думи ("Ctrl+Alt+Мечок").
_HOMOGLYPHS = {
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}
_CYR = re.compile(r"[Ѐ-ӿ]")
_LAT = re.compile(r"[A-Za-z]")

# --- 4. Епизодни означения -------------------------------------------------
# Реалната форма е ", сез.1, еп.41". Останалите варианти са защитни: източникът
# е чужд и може да смени формата си, а цената на едно допълнително разклонение
# в regex-а е нула.
_EPISODE_CUT = re.compile(
    r"[,\s]*(?:"
    r"сез(?:он)?\.?\s*\d+"          # сез.1 / сезон 1
    r"|еп(?:изод)?\.?\s*\d+"        # еп.41 / епизод 41
    r"|\bs\d{1,2}\s*e\d{1,3}\b"     # s02e05
    r"|\b[IVX]{1,4}\s+сезон\b"      # II сезон
    r")",
    re.IGNORECASE,
)

# Опашка ", 2023. Режисьор: ..." когато няма сез./еп. маркер
_YEAR_TAIL = re.compile(r",\s*(?:19|20)\d{2}\s*\..*$")

# Маркери за повторение / новост. В текущите данни ги няма нито веднъж, но са
# евтини и се появяват при почти всеки друг български източник.
_MARKERS = re.compile(
    r"(?:^|\s)(?:\(\s*п(?:овторение)?\s*\)|/\s*п\s*/|\bново\s*:|\bпремиера\s*:?|\bnew\b)",
    re.IGNORECASE,
)

# Жанрови опашки
_GENRE_TAIL = re.compile(
    r",\s*(?:анимаци\w*|сериал\w*|филм\w*|детск\w*)\s*$"
    r"|\((?:анимационен филм|анимация|сериал)\)\s*$",
    re.IGNORECASE,
)

# Сезонен суфикс "Bluey S1" -> "Bluey"
_SEASON_SUFFIX = re.compile(r"\s+S\d{1,2}\s*$", re.IGNORECASE)

_MULTISPACE = re.compile(r"\s+")
_EDGE_JUNK = re.compile(r"^[\s\-–—,.:;!?\"']+|[\s\-–—,.:;\"']+$")


def _fold_homoglyphs(text: str) -> str:
    """Замества латински двойници с кирилски — само в думи с кирилско мнозинство.

    Прави се на ниво дума, а не на ниво низ, за да оцелеят законно смесените
    случаи: "Hubby и приятeлчeтата му" -> "Hubby и приятелчетата му".
    """
    if not _CYR.search(text) or not _LAT.search(text):
        return text

    # Дали целият низ е кирилски по мнозинство — нужно е за самостоятелните
    # едно-буквени думи по-долу.
    cyrillic_text = len(_CYR.findall(text)) > len(_LAT.findall(text))

    out = []
    for token in re.split(r"(\s+)", text):
        cyr = _CYR.findall(token)
        lat = _LAT.findall(token)

        # Самостоятелна кратка дума без нито една кирилска буква: "Каква e
        # твоята профeсия?" — тук `e` е българското "е", но в думата няма
        # кирилица, с която да се сравни. Разчита се на контекста на низа.
        if not cyr and lat and len(token) <= 2 and cyrillic_text:
            if all(ch in _HOMOGLYPHS for ch in lat):
                out.append("".join(_HOMOGLYPHS.get(ch, ch) for ch in token))
                continue

        # Сгъва се само когато ВСЕКИ латински знак в думата е визуален двойник.
        # "щe" (само `e`) -> сгъва се. "Ctrl+Alt+Мечок" (`t`,`r`,`l` не са
        # двойници) -> не се пипа. Мнозинството само по себе си не стига:
        # в двубуквено "сe" кирилицата и латиницата са наравно.
        if cyr and lat and len(cyr) >= len(lat) and all(ch in _HOMOGLYPHS for ch in lat):
            token = "".join(_HOMOGLYPHS.get(ch, ch) for ch in token)
        out.append(token)
    return "".join(out)


def normalize_title(raw: str) -> str:
    """`raw_title` -> `raw_norm`, ключът около който се върти всичко.

    `raw_title` никога не се пипа — нормализацията е производна стойност,
    не замяна.

    ВХОДЪТ Е ВИНАГИ СУРОВО ЗАГЛАВИЕ. Функцията нарочно НЕ е идемпотентна и не
    може да бъде: рязането по тире се прилага само когато няма сезонен маркер,
    а след първото минаване маркерът вече го няма. Второ минаване би отрязало
    твърде много:

        "Кунг Фу Панда - Легенди за страхотният боец"  -> "кунг фу панда"
        "Трансформърс - Земна искра"                   -> "трансформърс"
        "i - Карли"                                    -> "i"

    Това са различни сериали, а не епизоди — сливането им е загуба на
    информация. Затова ръчно поддържаните CSV файлове пазят СУРОВИ заглавия и
    се нормализират при зареждане; никъде не се подава вече нормализиран ключ.
    """
    if not raw:
        return ""

    # 1. Unicode NFC + trim + свиване на интервали
    s = unicodedata.normalize("NFC", raw).strip()

    # 2. Уеднаквяване на пунктуация
    s = "".join(_PUNCT.get(ch, ch) for ch in s)
    s = _MULTISPACE.sub(" ", s)

    # 3. Хомоглифи (преди всяко сравнение на низове)
    s = _fold_homoglyphs(s)

    # 4. Маркери за повторение/новост
    s = _MARKERS.sub(" ", s)

    # 5. Епизодни означения — реже цялата опашка след първото попадение.
    #    Ако е сработило, тирето НЕ се пипа: заглавието вече е чисто и може
    #    само по себе си да съдържа " - ".
    cut = _EPISODE_CUT.search(s)
    if cut:
        s = s[: cut.start()]
    else:
        # Граматика 2: "ЗАГЛАВИЕ - Име на епизод"
        s = _YEAR_TAIL.sub("", s)
        parts = re.split(r"\s+-\s+", s, maxsplit=1)
        s = parts[0]
        s = _SEASON_SUFFIX.sub("", s)

    # 6. Жанрови опашки
    s = _GENRE_TAIL.sub("", s)

    # 7. Малки букви + почистване на ръбовете
    s = _EDGE_JUNK.sub("", s)
    s = _MULTISPACE.sub(" ", s).strip().lower()

    return s
