# --- Пунктуация и unicode --------------------------------------------------

def test_quotes_and_dashes_unified():
    # Кавичките по ръбовете отпадат изцяло — „Мечо Пух“ и Мечо Пух трябва да
    # са един ключ, а не два.
    assert N("„Мечо Пух“") == "мечо пух"
    assert N('"Мечо Пух"') == "мечо пух"
    assert N("Мечо Пух – Гората") == "мечо пух"   # en dash се държи като тире


def test_nfc_normalization():
    """Разложено `й` (и + U+0306) трябва да съвпадне със слятото."""
    assert N("Майки") == N("Майки")


def test_whitespace_collapsed():
    assert N("  Мечо   \t Пух  ") == "мечо пух"


@pytest.mark.parametrize("raw", ["", "   ", None])
def test_empty_input(raw):
    assert N(raw) == ""


def test_raw_title_is_never_mutated():
    """Нормализацията е производна стойност, не замяна."""
    raw = "Спонджбоб Квадратни Гащи, сез.9, еп.10"
    before = raw
    N(raw)
    assert raw == before


def test_stable_for_titles_without_a_dash():
    """За заглавия без тире второто минаване не променя нищо."""
    for raw, _ in GRAMMAR_SEASON_EPISODE + HOMOGLYPHS + GRAMMAR_BARE:
        once = N(raw)
        if " - " not in once:
            assert N(once) == once, raw


@pytest.mark.parametrize(
    "raw,after_one,after_two",
    [
        (
            "Кунг Фу Панда - Легенди за страхотният боец, сез.2, еп.7",
            "кунг фу панда - легенди за страхотният боец",
            "кунг фу панда",
        ),
        ("Трансформърс - Земна искра, сез.1, еп.3", "трансформърс - земна искра", "трансформърс"),
        ("i - Карли, сез.1, еп.2", "i - карли", "i"),
    ],
)
def test_double_normalization_would_lose_information(raw, after_one, after_two):
    """Заковава границата: подава се СУРОВО заглавие, никога вече нормализирано.

    Второто минаване реже до различен сериал ("Transformers: EarthSpark" ->
    "Transformers", "iCarly" -> "i"). Тестът пази това като известно и
    нарочно поведение, за да не го „поправи" някой в грешната посока.
    """
    assert N(raw) == after_one
    assert N(after_one) == after_two
    assert after_one != after_two
